/**
 * Packs PDF.js (legacy build) into a TS module of plain-script strings for the in-app WebView
 * renderer: no ES modules, no import.meta, no network. Runs on postinstall; output is gitignored.
 */
const fs = require('fs');
const path = require('path');

const dir = path.join(__dirname, '..', 'node_modules', 'pdfjs-dist', 'legacy', 'build');
const out = path.join(__dirname, '..', 'src', 'pdf', 'pdfjsSource.generated.ts');

/** "export{a as B,c as D};" at the end of a module -> "return {B:a,D:c};" inside a function. */
function toScript(code, globalName) {
  const m = /export\s*\{([^}]*)\}\s*;?\s*$/.exec(code);
  if (!m) throw new Error(`no trailing export list for ${globalName}`);
  const body = code.slice(0, m.index).replace(/import\.meta\.url/g, '""');
  const pairs = m[1].split(',').map((s) => s.trim()).filter(Boolean).map((s) => {
    const [local, exported] = s.split(/\s+as\s+/);
    return `${JSON.stringify(exported || local)}:${local}`;
  });
  return `globalThis.${globalName}=(function(){${body}\n;return {${pairs.join(',')}};})();`;
}

const lib = toScript(fs.readFileSync(path.join(dir, 'pdf.min.mjs'), 'utf8'), 'pdfjsLib');
const worker = toScript(fs.readFileSync(path.join(dir, 'pdf.worker.min.mjs'), 'utf8'), 'pdfjsWorker');
const version = require(path.join(dir, '..', '..', 'package.json')).version;

fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(
  out,
  `/* Generated by scripts/gen-pdfjs.js from pdfjs-dist ${version}. Do not edit. */\n` +
    `export const PDFJS_VERSION = ${JSON.stringify(version)};\n` +
    `export const PDFJS_WORKER_SCRIPT = ${JSON.stringify(worker)};\n` +
    `export const PDFJS_SCRIPT = ${JSON.stringify(lib)};\n`,
);
console.log(`gen-pdfjs: wrote ${path.relative(process.cwd(), out)} (${Math.round(fs.statSync(out).size / 1024)} KB)`);
